#!/usr/bin/env python3
"""Generate rtl/guncal_text.v, the GunCal core's on-screen text map, from the layout below.

Each layout line is (page, row, text). {name} marks a dynamic field whose width is given in FIELDS; the Verilog
module takes one input per field (ASCII, first character in the top byte) and returns the character for any
(page, row, column) of the 33 x 15 text screen. Run:  python cores/GunCal/tools/gen_text.py
"""
import os
import re

COLS, ROWS = 33, 15
PAGES = 3     # 0 = monitor, 1 = calibration, 2 = check

FIELDS = {          # name: width in characters
	'nowx': 4, 'nowy': 4, 'lastx': 4, 'lasty': 4, 'px': 4, 'py': 4,
	'light': 3, 'lock': 8, 'evs': 4, 'trig': 4, 'pulls': 4,
	'minx': 4, 'maxx': 4, 'miny': 4, 'maxy': 4,
	'pt': 1, 'np': 1, 'msg': 22,
}

LAYOUT = [          # (page, row, text)
	(0, 0, 'GUNCON2 CALIBRATION CORE'),
	(0, 2, 'NOW  X:{nowx}  Y:{nowy}'),
	(0, 3, 'LAST X:{lastx}  Y:{lasty}'),
	(0, 4, 'PICTURE X:{px}  Y:{py}'),
	(0, 5, 'LIGHT:{light}'),
	(0, 6, 'LOCK :{lock}'),
	(0, 7, 'EVENTS/S:{evs}'),
	(0, 8, 'TRIGGER:{trig}  PULLS:{pulls}'),
	(0, 10, 'X RANGE:{minx}-{maxx}'),
	(0, 11, 'Y RANGE:{miny}-{maxy}'),
	(0, 13, 'HOLD THE TRIGGER 3 SECONDS'),
	(0, 14, 'TO CALIBRATE AGAIN'),
	(1, 1, '         GUN CALIBRATION'),
	(1, 4, '   AIM AT THE CROSS AND SHOOT'),
	(1, 5, '   POINT {pt} OF {np}'),
	(1, 11, '   {msg}'),
	(1, 12, '   D-PAD: MOVE CROSSES IN OR OUT'),
	(1, 13, '   HOLD TRIGGER 3 SEC: RESTART'),
	(2, 1, '         GUN CALIBRATION'),
	(2, 4, '   IS THE GUN SIGHT ALIGNED?'),
	(2, 5, '   SHOOT THE RING TO CHECK'),
	(2, 11, '   RETRY: HOLD TRIGGER 3 SEC'),
	(2, 12, '   END: PRESS A OR B'),
]


def expand(text):
	"""-> list of (kind, value) per column: ('c', ascii) or ('f', (name, index))."""
	out = []
	for tok in re.split(r'(\{\w+\})', text):
		if not tok:
			continue
		if tok.startswith('{'):
			name = tok[1:-1]
			for i in range(FIELDS[name]):
				out.append(('f', (name, i)))
		else:
			out.extend(('c', ord(c)) for c in tok)
	assert len(out) <= COLS, (text, len(out))
	return out


def main():
	used = sorted({v[0] for _, _, t in LAYOUT for k, v in expand(t) if k == 'f'})
	lines = ['// Generated by tools/gen_text.py. Do not edit.', 'module guncal_text(', '\tinput [1:0] page,',
	         '\tinput [3:0] row,', '\tinput [5:0] col,']
	for n in used:
		lines.append('\tinput [%d:0] %s,' % (FIELDS[n] * 8 - 1, n))
	lines += ['\toutput reg [7:0] ch', ');', 'always @* begin', "\tch = 8'h20;", '\tcase ({page, row, col})']
	for page, row, text in LAYOUT:
		for col, (kind, v) in enumerate(expand(text)):
			if kind == 'c':
				if v != 0x20:
					lines.append("\t\t{2'd%d, 4'd%d, 6'd%d}: ch = 8'h%02x;" % (page, row, col, v))
			else:
				name, i = v
				lines.append("\t\t{2'd%d, 4'd%d, 6'd%d}: ch = %s[%d +: 8];" % (page, row, col, name, (FIELDS[name] - 1 - i) * 8))
	lines += ['\t\tdefault: ch = 8\'h20;', '\tendcase', 'end', 'endmodule', '']
	path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'rtl', 'guncal_text.v')
	open(path, 'w', newline='\n').write('\n'.join(lines))
	print('wrote', os.path.normpath(path), '(%d fields)' % len(used))


if __name__ == '__main__':
	main()
