"""Generate rtl/font5x7.v: a 5x7 pixel font for the debug core's on-screen text.

Glyphs are drawn here as ASCII art (# = pixel) so they can be checked by eye:
  python cores/GunDebug/tools/gen_font.py --show     print every glyph
  python cores/GunDebug/tools/gen_font.py            write cores/GunDebug/rtl/font5x7.v
The Verilog module takes a 6-bit character index and a row 0..6 and returns 5 bits (bit 4 = leftmost pixel).
"""
