ORDER = ' 0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ:.-=/+%()><#!?_*,|'
assert len(ORDER) <= 64 and set(ORDER) == set(G), set(G) ^ set(ORDER)


def show():
	for ch in ORDER:
		print(repr(ch), ORDER.index(ch))
		for r in G[ch]:
			print('   ' + r.replace('.', ' '))


def verilog():
	out = ['// Generated by tools/gen_font.py. Do not edit.', 'module font5x7(input [5:0] ch, input [2:0] row, output reg [4:0] bits);',
	       'always @* begin', '\tcase ({ch, row})']
	for i, ch in enumerate(ORDER):
		for row in range(7):
			bits = int(G[ch][row].replace('#', '1').replace('.', '0'), 2)
			out.append("\t\t{6'd%d, 3'd%d}: bits = 5'b%s;" % (i, row, format(bits, '05b')))
	out += ["\t\tdefault: bits = 5'b00000;", '\tendcase', 'end', 'endmodule', '']
	out += ['', '// ASCII code -> index into the font above (unknown characters are spaces)',
	        'module font_idx(input [7:0] a, output reg [5:0] i);', 'always @* begin', '\tcase (a)']
	for i, ch in enumerate(ORDER):
		out.append("\t\t8'd%d: i = 6'd%d;  // %s" % (ord(ch), i, ch if ch != ' ' else 'space'))
	out += ["\t\tdefault: i = 6'd0;", '\tendcase', 'end', 'endmodule', '']
	return '\n'.join(out)


def index_table():
	return '\n'.join("localparam [5:0] C_%s = 6'd%d;" % (
		{' ': 'SP', ':': 'COLON', '.': 'DOT', '-': 'DASH', '=': 'EQ', '/': 'SLASH', '+': 'PLUS', '%': 'PCT', '(': 'LP', ')': 'RP',
		 '>': 'GT', '<': 'LT', '#': 'HASH', '!': 'BANG', '?': 'Q', '_': 'US', '*': 'STAR', ',': 'COMMA', '|': 'BAR'}.get(c, c), i)
		for i, c in enumerate(ORDER))


if __name__ == '__main__':
	if '--show' in sys.argv:
		show()
	elif '--index' in sys.argv:
		print(index_table())
	else:
		path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'rtl', 'font5x7.v')
		os.makedirs(os.path.dirname(path), exist_ok=True)
		open(path, 'w', newline='\n').write(verilog())
		print('wrote', os.path.normpath(path))
